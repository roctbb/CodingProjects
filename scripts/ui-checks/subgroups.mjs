export default async function subgroups(controlPage, {url, output, widths=[1440,390,320]}) {
    const results=[], errors=[];
    const check=(name,passed,width,details={})=>{results.push({name,passed,width,...details});if(!passed)throw new Error(name+': '+JSON.stringify(details));};
    for(const width of widths) {
        const context=await controlPage.context().browser().newContext({viewport:{width,height:1000},isMobile:width<600,hasTouch:width<600,reducedMotion:'reduce'});
        const page=await context.newPage();
        page.on('pageerror',error=>errors.push({name:'subgroups-js',width,message:error.message}));
        const scenario=width>600?'subgroups-desktop':'subgroups-phone';
        const query=new URLSearchParams({actor:'teacher',scenario});
        try {
            await page.goto(`${url}/insider/courses/1/subgroups?${query}`);
            const createToggle=page.getByRole('button',{name:'+ Подгруппа',exact:true});
            await createToggle.waitFor();
            await page.locator('[data-subgroup-selection]').waitFor();
            check('subgroups-create-and-transfer-hidden-by-default',!await page.locator('[data-subgroup-create]').isVisible()&&!await page.locator('[data-subgroup-transfer]').isVisible()&&!await page.locator('[data-subgroup-clear]').isVisible(),width);
            await createToggle.click();
            await page.getByLabel('Название новой подгруппы').fill('Не сохранено');
            await page.getByLabel('Название новой подгруппы').press('Escape');
            check('subgroups-create-cancel-restores-focus',!await page.locator('[data-subgroup-create]').isVisible()&&await createToggle.evaluate(el=>el===document.activeElement),width);
            check('subgroups-management-loads',await page.locator('input[name="students[]"]').count()===4,width);
            check('subgroups-management-no-overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            const group=page.locator('[data-subgroup-editor]').first();
            const rename=group.locator('[data-subgroup-edit-form]');
            check('subgroups-rename-closed-by-default',!await rename.isVisible(),width);
            await group.locator('[data-subgroup-edit]').click();
            const name=rename.locator('[name="name"]');
            const original=await name.inputValue();
            await name.fill('Несохранённое название');
            await name.press('Escape');
            check('subgroups-rename-cancel-restores-value-and-focus',!await rename.isVisible()&&await name.inputValue()===original&&await group.locator('[data-subgroup-edit]').evaluate(el=>el===document.activeElement),width);
            await group.locator('[data-subgroup-edit]').click();
            check('subgroups-rename-no-overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            await page.screenshot({path:`${output}/subgroups-rename-${width}.png`,fullPage:true});
            if(width===1440) {
                await name.fill(original+' · обновлена');
                await rename.getByRole('button',{name:'Сохранить',exact:true}).click();
                await page.locator('.gc-subgroup-title').filter({hasText:original+' · обновлена'}).waitFor();
                check('subgroups-rename-saves',true,width);
            } else await rename.getByRole('button',{name:'Отменить переименование',exact:true}).click();
            const master=page.getByRole('checkbox',{name:'Выбрать всех учеников',exact:true});
            await master.check();
            check('subgroups-select-all',await page.locator('input[name="students[]"]:checked').count()===4,width);
            await page.locator('input[name="students[]"][value="1"]').uncheck();
            check('subgroups-partial-selection',await master.evaluate(el=>el.indeterminate)&&await page.getByRole('status').filter({hasText:'Выбрано: 3'}).count()===1,width);
            await page.getByRole('button',{name:'Выбрать без подгруппы (1)',exact:true}).click();
            check('subgroups-select-only-unassigned',JSON.stringify(await page.locator('input[name="students[]"]:checked').evaluateAll(inputs=>inputs.map(input=>input.value)))==='["6"]',width);
            await page.getByRole('button',{name:'Снять выбор',exact:true}).click();
            check('subgroups-clear-selection',await page.locator('[data-subgroup-roster] input[name="students[]"]:checked').count()===0&&!await master.evaluate(el=>el.indeterminate)&&!await page.locator('[data-subgroup-transfer]').isVisible(),width);
            await page.screenshot({path:`${output}/subgroups-management-${width}.png`,fullPage:true});
            if(width===1440) {
                await createToggle.click();
                await page.getByLabel('Название новой подгруппы').fill(original+' · обновлена');
                await page.getByRole('button',{name:'Создать подгруппу',exact:true}).click();
                await page.locator('[data-subgroup-create][data-open="true"]').waitFor();
                check('subgroups-create-validation-keeps-form-and-name',await page.getByLabel('Название новой подгруппы').inputValue()===original+' · обновлена',width);
                await page.getByLabel('Название новой подгруппы').fill('Подгруппа В · новая');
                await page.getByRole('button',{name:'Создать подгруппу',exact:true}).click();
                await page.locator('#subgroup-target option').filter({hasText:'Подгруппа В · новая'}).waitFor({state:'attached'});
                check('subgroups-new-group-is-transfer-target',await page.locator('#subgroup-target option:checked').textContent()==='Подгруппа В · новая',width);
                await page.getByRole('button',{name:'Добавить оставшихся — 1',exact:true}).click();
                const moved=page.locator('tbody tr').filter({hasText:'Ученик 6'});
                await moved.getByText('Подгруппа В · новая',{exact:true}).waitFor();
                check('subgroups-create-and-add-remaining',await page.locator('tbody tr').filter({hasText:'Ученик 4'}).innerText().then(text=>text.includes('Подгруппа Б')),width);
                await moved.locator('input[type="checkbox"]').check();
                await page.locator('#subgroup-target').selectOption('');
                await page.getByRole('button',{name:'Перевести',exact:true}).click();
                await moved.getByText('Без подгруппы',{exact:true}).waitFor();
                check('subgroups-manual-transfer',true,width);
            }
            await page.goto(`${url}/insider/courses/1?${query}&subgroup=1`);
            const leaderboard=page.locator('#course-leaderboard + ul');
            const names=await leaderboard.innerText();
            check('subgroups-teacher-ranking',names.includes('Ученик 1')&&names.includes('Ученик 3')&&!names.includes('Ученик 4'),width);
            await page.getByRole('link',{name:'Отчёт',exact:true}).click();
            await page.locator('[data-report-workspace]').waitFor();
            await page.locator('#student1[data-report-loaded="true"]').waitFor();
            if(width>768) check('subgroups-report-roster-visible',await page.locator('#report-students-title').isVisible(),width,await page.locator('#report-students-title').evaluate(el=>({visibility:getComputedStyle(el).visibility,display:getComputedStyle(el).display,box:el.getBoundingClientRect().toJSON(),parent:el.closest('aside').outerHTML.slice(0,300)})));
            if(width>768) {
                await page.locator('#student3-tab').click();
                await page.locator('#student3[data-report-loaded="true"]').waitFor();
                await page.locator('.gc-report-roster').screenshot({path:`${output}/subgroups-roster-${width}.png`});
            }
            check('subgroups-report-keeps-context',new URL(page.url()).searchParams.get('subgroup')==='1'&&await page.locator('#v-pills-tab [data-report-student-name]').count()===2,width);
            check('subgroups-report-no-overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            await page.screenshot({path:`${output}/subgroups-report-${width}.png`,fullPage:true});
            await page.goto(`${url}/insider/courses/1/report?${query}&subgroup=all`);
            await page.locator('[data-scope-statistics] > summary').click();
            await page.getByRole('link',{name:'Подгруппа Б · вечерняя',exact:true}).waitFor();
            await page.screenshot({path:`${output}/subgroups-comparison-${width}.png`,fullPage:true});
            await page.evaluate(()=>document.documentElement.dataset.bsTheme='dark');
            await page.screenshot({path:`${output}/subgroups-comparison-dark-${width}.png`,fullPage:true});
            await page.goto(`${url}/insider/courses/1/planner?${query}&subgroup=1`);
            await page.locator('.planner-session').first().waitFor();
            check('subgroups-calendar-isolation',(await page.locator('#planner-calendar').innerText()).includes('Практика А')&&!(await page.locator('#planner-calendar').innerText()).includes('Практика Б'),width);
            check('subgroups-calendar-no-overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            await page.screenshot({path:`${output}/subgroups-planner-${width}.png`,fullPage:true});
            const source=page.locator('.planner-session:not([data-read-only])').filter({hasText:'Практика А'});
            check('subgroups-calendar-avoids-repeated-scope-label',await source.locator('.planner-session-audience').count()===0&&await page.locator('.planner-session[data-read-only] .planner-session-audience').filter({hasText:'Общее занятие'}).count()>0,width);
            check('subgroups-common-calendar-link-is-compact',await page.locator('.planner-session[data-read-only] .planner-session-footer').count()===0&&await page.getByRole('link',{name:'Общее занятие — открыть общее расписание',exact:true}).first().getAttribute('href').then(href=>href.endsWith('subgroup=all')),width);
            await source.locator('.planner-session-menu > summary').click();
            await source.getByRole('button',{name:'Скопировать материалы в…'}).click();
            await page.locator('#planner-dialog[open] select[name="target_session_id"]').waitFor();
            check('subgroups-copy-offers-other-group',await page.locator('#planner-dialog select option').filter({hasText:'Подгруппа Б'}).count()>0,width);
            if(width===1440) {
                const target=page.locator('#planner-dialog select option').filter({hasText:'Подгруппа Б'}).first();
                const targetId=await target.getAttribute('value');
                await page.locator('#planner-dialog select').selectOption(targetId);
                await page.locator('#planner-dialog [type="submit"]').click();
                await page.locator('#planner-dialog').waitFor({state:'hidden'});
                const response=await page.request.get(`${url}/insider/courses/1/planner/api/state?subgroup=2&from=2026-11-09&to=2026-11-15`);
                const state=await response.json();
                check('subgroups-copy-saves-to-other-calendar',response.ok()&&state.sessions.find(s=>String(s.id)===targetId)?.entries.length===2,width);
            } else await page.locator('#planner-dialog [data-action="close-dialog"]').first().click();
            await page.goto(`${url}/insider/courses/1/planner?${query}&subgroup=all`);
            await page.locator('.planner-session-audience').first().waitFor();
            check('subgroups-all-calendars-keep-scope-labels',await page.locator('.planner-session-audience').filter({hasText:'Подгруппа А'}).count()>0&&await page.locator('.planner-session-audience').filter({hasText:'Подгруппа Б'}).count()>0,width);
            await page.screenshot({path:`${output}/subgroups-planner-all-${width}.png`,fullPage:true});
            await page.goto(`${url}/insider/courses/1?actor=student&scenario=${scenario}&subgroup=2`);
            const studentNames=await page.locator('#course-leaderboard + ul').innerText();
            check('subgroups-student-cannot-switch',studentNames.includes('Ученик 3')&&!studentNames.includes('Ученик 4')&&await page.locator('#course-subgroup').count()===0,width);
            await page.getByRole('link',{name:'План занятий',exact:true}).click();
            await page.getByRole('heading',{name:'Практика А',exact:true}).waitFor();
            check('subgroups-student-calendar',await page.getByRole('heading',{name:'Практика Б',exact:true}).count()===0&&await page.getByRole('button',{name:'Добавить'}).count()===0,width);
            check('subgroups-student-no-overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            await page.screenshot({path:`${output}/subgroups-student-${width}.png`,fullPage:true});
            await page.evaluate(()=>document.documentElement.dataset.bsTheme='dark');
            await page.screenshot({path:`${output}/subgroups-student-dark-${width}.png`,fullPage:true});

            const largeQuery=new URLSearchParams({actor:'teacher',scenario:width>600?'subgroups-large-desktop':'subgroups-large-phone'});
            await page.goto(`${url}/insider/courses/1/subgroups?${largeQuery}`);
            const search=page.getByRole('searchbox',{name:'Найти ученика',exact:true});
            await search.waitFor();
            const roster=page.locator('[data-subgroup-roster]');
            const boxes=roster.locator('input[name="students[]"]');
            check('subgroups-large-class-has-search',await boxes.count()===30,width);
            await boxes.last().check();
            const sticky=await page.locator('.gc-subgroup-roster-toolbar').evaluate(el=>({top:el.getBoundingClientRect().top,offset:document.querySelector('.gc-topbar').getBoundingClientRect().height}));
            check('subgroups-actions-stay-visible-while-scrolling',sticky.top>=sticky.offset&&sticky.top<=sticky.offset+20,width,sticky);
            await page.screenshot({path:`${output}/subgroups-sticky-${width}.png`});
            await search.fill('Ученик 1');
            const found=page.getByRole('checkbox',{name:'Выбрать найденных учеников',exact:true});
            await found.check();
            const selectedIds=await roster.locator('input[name="students[]"]:checked').evaluateAll(inputs=>inputs.map(input=>input.value));
            const selectionText=await roster.locator('[data-subgroup-selected-count]').innerText();
            check('subgroups-search-keeps-hidden-selection',selectedIds.length===13&&selectedIds.includes('31')&&selectionText.includes('вне поиска: 1'),width,{selectedIds,selectionText});
            await found.uncheck();
            check('subgroups-select-all-only-affects-found',await roster.locator('input[name="students[]"]:checked').count()===1,width);
            await search.fill('ученика с таким именем нет');
            await page.locator('[data-subgroup-search-empty]').waitFor();
            check('subgroups-empty-search',await found.isDisabled(),width);
            await page.getByRole('button',{name:'Снять выбор',exact:true}).click();
            check('subgroups-clear-hidden-selection',await roster.locator('input[name="students[]"]:checked').count()===0&&!await roster.locator('[data-subgroup-transfer]').isVisible(),width);
            await page.getByRole('button',{name:'Сбросить поиск',exact:true}).click();
            await search.fill('федоров артем');
            check('subgroups-search-normalizes-russian-names',await roster.locator('tbody tr:not([hidden]) input[name="students[]"]').count()===1&&await roster.locator('tbody tr:not([hidden]) input[name="students[]"]').inputValue()==='31',width);
            await search.press('Escape');
            check('subgroups-search-reset-and-long-names-fit',await roster.locator('tbody tr:not([hidden]) input[name="students[]"]').count()===30&&await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width);
            await page.screenshot({path:`${output}/subgroups-large-${width}.png`,fullPage:true});
        } finally {await context.close();}
    }
    return {results,errors};
}
